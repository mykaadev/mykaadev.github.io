module Jekyll
  module PluginSync
    class Engine
      PAGE_AUTOGEN_MARKER = "autogenerated: true"
      INCLUDE_AUTOGEN_HEADER = "<!-- AUTO-GENERATED by plugin_sync. Do not edit manually. -->\n\n"
      # A line that is only an image link to an .html file in the showcase folder: [![alt](picture)](Showcase/Name.html)
      SHOWCASE_LINK = /^[ \t]*\[!\[[^\]]*\]\([^)]*\)\]\(([^)\s]+\.html)\)[ \t]*$/i
      SHOWCASE_MANIFEST = ".plugin_sync.json"
      SHOWCASE_EXTENSIONS = %w[.html .css .js .json .svg .png .jpg .jpeg .webp .gif .avif .mp4 .webm .woff .woff2 .txt].freeze
      SHOWCASE_MAX_FILE_BYTES = 10 * 1024 * 1024
      MARKDOWN_LINK = /(?<!!)\[([^\]]+)\]\(([^)\s]+)\)/
      DOC_CARD_LINE = /\A\s*[-*]\s+\[([^\]]+)\]\(([^)\s]+)\)\s*(?:[-–—:]\s*(.*?))?\s*\z/
      MAX_DOC_PAGES = 20

      DEFAULT_CONFIG = {
        "enabled" => true,
        "github_user" => "mykaadev",
        "include_topics" => [],
        "include_repo_prefixes" => ["Ns"],
        "allow_prefix_fallback" => true,
        "include_repos" => [],
        "exclude_repos" => [],
        "include_archived" => false,
        "default_category" => "Utility",
        "default_thumbnail" => "/resources/images/plugins/UtilityAI.png",
        "generated_pages_dir" => "_generated/plugins",
        "generated_readmes_dir" => "_includes/generated/readmes",
        "readme_include_dir" => "generated/readmes",
        "download_footer" => true,
        "cleanup_when_empty" => false,
        "showcase_dir" => "Docs/Showcase",
        "generated_showcases_dir" => "showcases",
        "category_by_topic" => {
          "algorithm" => "Algorithm",
          "gameplay" => "Gameplay",
          "tools" => "Tools",
          "utility" => "Utility",
          "visuals" => "Visuals"
        },
        "repo_overrides" => {},
        "discussions" => {
          "enabled" => true,
          "category" => "General",
          "mapping" => "specific",
          "term_prefix" => "plugin-",
          "repo_overrides" => {}
        }
      }.freeze

      def initialize(site)
        @site = site
        @source = site.source
        @config = deep_merge(DEFAULT_CONFIG, stringify_keys(site.config["plugin_sync"] || {}))
        @github_user = @config["github_user"].to_s.strip
        @github_token = ENV["PLUGIN_SYNC_GITHUB_TOKEN"] || ENV["GITHUB_TOKEN"]
        @discussion_category_cache = {}
        # Local preview: read README and showcase files from local clones instead of GitHub
        @local_root = ENV["PLUGIN_SYNC_LOCAL_ROOT"].to_s.strip.tr("\\", "/")
        @local_repos = ENV["PLUGIN_SYNC_LOCAL_REPOS"].to_s.split(",").map(&:strip).reject(&:empty?)
      end

      def sync!
        return unless truthy?(@config["enabled"])
        return if @github_user.empty?

        FileUtils.mkdir_p(readmes_dir)
        FileUtils.mkdir_p(pages_dir)

        repos = fetch_public_repositories
        remote_listed = !repos.empty?
        repos.concat(local_only_repositories(repos))
        if repos.empty?
          Jekyll.logger.warn("[plugin_sync] No repositories found for '#{@github_user}'. Keeping previous generated files.")
          return
        end

        generated_repo_names = []
        matched_candidates = 0

        repos.each do |repo|
          next unless repository_allowed?(repo)

          repo_name = repo["name"].to_s
          topics = repo["local_only"] ? [] : fetch_repository_topics(repo_name)
          next unless plugin_repository?(repo_name, topics)

          matched_candidates += 1
          branch = repo["default_branch"].to_s.empty? ? "main" : repo["default_branch"].to_s
          readme_body = local_repo_dir(repo_name) ? read_local_file(repo_name, "README.md") : fetch_readme(repo_name, branch)
          if readme_body.nil? || readme_body.empty?
            Jekyll.logger.warn("[plugin_sync] README missing for #{repo_name}, skipping.")
            next
          end

          normalized_readme, readme_meta = normalize_readme(readme_body, repo_name, branch)
          showcase = sync_showcase(repo_name, branch, readme_meta)
          page_data = build_page_data(repo, topics, readme_meta, branch)
          docs = sync_docs(repo_name, branch, normalized_readme, page_data, showcase)
          normalized_readme = inline_showcases(normalized_readme, "", showcase, repo_name, branch)
          normalized_readme = build_doc_cards(normalized_readme, docs, repo_name, branch)
          normalized_readme = rewrite_doc_links(normalized_readme, "", docs, page_data, repo_name, branch)
          write_readme_include(repo_name, normalized_readme)
          write_plugin_page(repo_name, page_data)

          generated_repo_names << repo_name
          Jekyll.logger.info("[plugin_sync] Synced #{repo_name}")
        end

        if matched_candidates.zero?
          Jekyll.logger.warn("[plugin_sync] No repositories matched plugin filters. Keeping previous generated files.")
          return
        end

        if generated_repo_names.empty?
          Jekyll.logger.warn("[plugin_sync] No plugin pages were generated. Keeping previous generated files.")
          return
        end

        # A failed GitHub listing leaves only the local repos, so keep the pages of the others
        if remote_listed
          cleanup_stale_generated_files(generated_repo_names)
        else
          Jekyll.logger.warn("[plugin_sync] GitHub listed no repositories. Skipping cleanup of other plugin pages.")
        end
        Jekyll.logger.info("[plugin_sync] Generated #{generated_repo_names.size} plugin page(s).")
      end

      private

      def readmes_dir
        File.join(@source, @config["generated_readmes_dir"].to_s)
      end

      def pages_dir
        File.join(@source, @config["generated_pages_dir"].to_s)
      end

      def readme_include_dir
        @config["readme_include_dir"].to_s
      end

      def showcases_dir
        File.join(@source, @config["generated_showcases_dir"].to_s)
      end

      def local_repo_dir(repo_name)
        return nil if @local_root.empty?

        path = File.join(@local_root, repo_name)
        File.directory?(path) ? path : nil
      end

      def read_local_file(repo_name, relative_path)
        path = File.join(local_repo_dir(repo_name).to_s, relative_path)
        File.file?(path) ? File.read(path, mode: "rb").force_encoding("UTF-8") : nil
      end

      # Repositories named in PLUGIN_SYNC_LOCAL_REPOS that GitHub does not list (private or not pushed yet)
      def local_only_repositories(listed_repos)
        listed_names = listed_repos.map { |repo| repo["name"].to_s }
        @local_repos.filter_map do |repo_name|
          next if listed_names.include?(repo_name)

          repo_dir = local_repo_dir(repo_name)
          if repo_dir.nil?
            Jekyll.logger.warn("[plugin_sync] Local repo #{repo_name} not found under #{@local_root}.")
            next
          end

          Jekyll.logger.info("[plugin_sync] Using local-only repo #{repo_name} from #{repo_dir}")
          descriptor_path = File.join(repo_dir, "#{repo_name}.uplugin")
          descriptor = File.file?(descriptor_path) ? (JSON.parse(File.read(descriptor_path, encoding: "bom|utf-8")) rescue {}) : {}
          {
            "name" => repo_name,
            "description" => descriptor["Description"].to_s,
            "default_branch" => "main",
            "html_url" => "https://github.com/#{@github_user}/#{repo_name}",
            "pushed_at" => File.mtime(repo_dir).utc.iso8601,
            "local_only" => true
          }
        end
      end

      # Mirrors the showcase folder of a plugin repo (small HTML fragments and their pictures) into the site.
      # Returns the folder in the repo, its URL, and its local copy, or nil when the repo has none.
      def sync_showcase(repo_name, branch, meta)
        showcase_dir = first_present(meta["showcase"], meta["showcase_dir"], @config["showcase_dir"]).sub(%r{\A/+}, "").sub(%r{/+\z}, "")
        target_dir = File.join(showcases_dir, slugify(repo_name))
        return nil if showcase_dir.empty?

        files = local_repo_dir(repo_name) ? list_local_showcase(repo_name, showcase_dir) : list_remote_showcase(repo_name, branch, showcase_dir)
        if files.empty?
          FileUtils.rm_rf(target_dir) if File.file?(File.join(target_dir, SHOWCASE_MANIFEST))
          return nil
        end

        manifest_path = File.join(target_dir, SHOWCASE_MANIFEST)
        previous = File.file?(manifest_path) ? (JSON.parse(File.read(manifest_path)) rescue {}) : {}
        current = {}

        files.each do |file|
          destination = File.join(target_dir, file["path"])
          current[file["path"]] = file["sha"]
          next if previous[file["path"]] == file["sha"] && File.file?(destination)

          body = file["local_path"] ? File.binread(file["local_path"]) : fetch_raw_file(repo_name, branch, "#{showcase_dir}/#{file["path"]}")
          if body.nil?
            Jekyll.logger.warn("[plugin_sync] Could not download showcase file #{file["path"]} for #{repo_name}.")
            current.delete(file["path"])
            next
          end

          FileUtils.mkdir_p(File.dirname(destination))
          File.binwrite(destination, body)
        end

        (previous.keys - current.keys).each { |stale| FileUtils.rm_f(File.join(target_dir, stale)) }
        FileUtils.mkdir_p(target_dir)
        File.write(manifest_path, JSON.pretty_generate(current)) unless previous == current

        Jekyll.logger.info("[plugin_sync] Synced showcase for #{repo_name} (#{current.size} file(s))")
        { "dir" => showcase_dir, "url" => "/#{@config["generated_showcases_dir"]}/#{slugify(repo_name)}/", "local" => target_dir }
      end

      def showcase_file?(path, size)
        SHOWCASE_EXTENSIONS.include?(File.extname(path).downcase) && size.to_i <= SHOWCASE_MAX_FILE_BYTES
      end

      def list_local_showcase(repo_name, showcase_dir)
        root = File.join(local_repo_dir(repo_name), showcase_dir)
        return [] unless File.directory?(root)

        Dir.glob(File.join(root, "**", "*")).filter_map do |path|
          next unless File.file?(path)

          relative = path.delete_prefix("#{root}/")
          next unless showcase_file?(relative, File.size(path))

          # Size and time stand in for the git blob sha, so unchanged files are not copied again
          { "path" => relative, "sha" => "#{File.size(path)}-#{File.mtime(path).to_i}", "local_path" => path }
        end
      end

      def list_remote_showcase(repo_name, branch, showcase_dir)
        payload = github_get_json("https://api.github.com/repos/#{@github_user}/#{repo_name}/git/trees/#{branch}?recursive=1")
        tree = payload.is_a?(Hash) ? Array(payload["tree"]) : []
        prefix = "#{showcase_dir}/"

        tree.filter_map do |entry|
          path = entry["path"].to_s
          next unless entry["type"] == "blob" && path.start_with?(prefix)

          relative = path.delete_prefix(prefix)
          next unless showcase_file?(relative, entry["size"])

          { "path" => relative, "sha" => entry["sha"].to_s }
        end
      end

      def fetch_raw_file(repo_name, branch, path)
        encoded_path = path.split("/").map { |segment| URI.encode_www_form_component(segment).gsub("+", "%20") }.join("/")
        response = http_get(URI("https://raw.githubusercontent.com/#{@github_user}/#{repo_name}/refs/heads/#{branch}/#{encoded_path}"))
        response.is_a?(Net::HTTPSuccess) ? response.body.to_s.b : nil
      rescue StandardError => e
        Jekyll.logger.warn("[plugin_sync] Error fetching #{path} for #{repo_name}: #{e.message}")
        nil
      end

      # A showcase link in a doc becomes the HTML of its fragment, so the site styles and runs it.
      # On GitHub the link shows its picture. The site drops scripts, styles, and event attributes of the fragment.
      def inline_showcases(content, base_dir, showcase, repo_name, branch)
        return content if showcase.nil?

        content.gsub(SHOWCASE_LINK) do
          original = Regexp.last_match(0)
          path, = resolve_repo_link(base_dir, Regexp.last_match(1), repo_name, branch)
          prefix = "#{showcase["dir"]}/"
          next original if path.nil? || !path.start_with?(prefix)

          relative = path.delete_prefix(prefix)
          source = File.join(showcase["local"], relative)
          unless File.file?(source)
            Jekyll.logger.warn("[plugin_sync] Showcase #{relative} missing for #{repo_name}.")
            next original
          end

          fragment_dir = File.dirname(relative) == "." ? "" : "#{File.dirname(relative)}/"
          fragment = clean_showcase_fragment(File.read(source, encoding: "bom|utf-8"), showcase["url"] + fragment_dir)
          "\n<div class=\"ns-showcase\">\n#{fragment}\n</div>\n"
        end
      end

      def clean_showcase_fragment(html, base_url)
        cleaned = html.gsub(/<!--.*?-->/m, "")
        cleaned = cleaned.gsub(%r{<(script|style)\b[^>]*>.*?</\1\s*>}im, "").gsub(/<link\b[^>]*>/i, "")
        cleaned = cleaned.gsub(/\s+on[a-z]+\s*=\s*(?:"[^"]*"|'[^']*'|[^\s>]+)/i, "")
        cleaned = cleaned.gsub(/(\s(?:src|href|poster|data-image)\s*=\s*["'])([^"']+)(["'])/i) do
          prefix, value, suffix = Regexp.last_match.captures
          next "#{prefix}#{value}#{suffix}" if value.match?(%r{\A(?:[a-z][a-z0-9+.-]*:|/|#)}i)

          "#{prefix}#{base_url}#{value.sub(%r{\A\./}, "")}#{suffix}"
        end
        # Kramdown ends an HTML block at a blank line, so the fragment keeps none
        cleaned.lines.map(&:rstrip).reject(&:empty?).join("\n")
      end

      # Markdown files that the README links to (and the files those link to) become pages under the plugin page.
      # On GitHub the links stay as they are.
      def sync_docs(repo_name, branch, readme, page_data, showcase)
        FileUtils.rm_rf(File.join(pages_dir, "docs", repo_name))
        docs = {}
        queue = doc_links(readme, "", repo_name, branch)

        until queue.empty? || docs.size >= MAX_DOC_PAGES
          path, link_text = queue.shift
          next if docs.key?(path)

          body = local_repo_dir(repo_name) ? read_local_file(repo_name, path) : fetch_raw_file(repo_name, branch, path)&.force_encoding("UTF-8")
          next if body.nil? || body.strip.empty?

          docs[path] = {
            "title" => link_text,
            "url" => "#{page_data["permalink"].chomp("/")}/#{doc_slug(path)}/",
            "body" => body
          }
          queue.concat(doc_links(body, File.dirname(path), repo_name, branch))
        end

        docs.each { |path, doc| write_doc_page(repo_name, branch, path, doc, docs, page_data, showcase) }
        Jekyll.logger.info("[plugin_sync] Synced #{docs.size} doc page(s) for #{repo_name}") unless docs.empty?
        docs
      end

      def doc_links(content, base_dir, repo_name, branch)
        content.to_s.scan(MARKDOWN_LINK).filter_map do |text, link|
          path, = resolve_repo_link(base_dir, link, repo_name, branch)
          next if path.nil? || !path.downcase.end_with?(".md") || path.casecmp?("README.md")

          [path, text.strip]
        end
      end

      # Returns [repo path, anchor] for a link into this repository, or nil for any other link
      def resolve_repo_link(base_dir, link, repo_name, branch)
        target = link.to_s.strip
        return nil if target.empty? || target.start_with?("#") || target.match?(/\A(?:mailto|data|javascript):/i)

        if target.match?(/\Ahttps?:\/\//i)
          uri = URI.parse(target)
          parts = uri.path.to_s.split("/")
          return nil unless uri.host == "github.com" && parts[1] == @github_user && parts[2] == repo_name
          return nil unless %w[blob tree].include?(parts[3]) && parts[4] == branch && parts.size > 5

          return [parts[5..].join("/"), uri.fragment.to_s]
        end

        relative, anchor = target.split("#", 2)
        segments = relative.start_with?("/") ? [] : base_dir.to_s.split("/").reject { |segment| segment.empty? || segment == "." }
        relative.split("/").each do |segment|
          next if segment.empty? || segment == "."

          segment == ".." ? segments.pop : segments << URI.decode_www_form_component(segment.gsub("+", "%2B"))
        end
        segments.empty? ? nil : [segments.join("/"), anchor.to_s]
      rescue StandardError
        nil
      end

      def doc_slug(path)
        slugify(File.basename(path, ".*").gsub(/([a-z0-9])([A-Z])/, "\\1-\\2"))
      end

      # A doc link goes to its synced page, a README link to the plugin page, and any other repo link to GitHub
      def rewrite_doc_links(content, base_dir, docs, page_data, repo_name, branch)
        content.gsub(MARKDOWN_LINK) do
          text = Regexp.last_match(1)
          link = Regexp.last_match(2)
          path, anchor = resolve_repo_link(base_dir, link, repo_name, branch)
          suffix = anchor.to_s.empty? ? "" : "##{anchor}"

          target = if path.nil?
                     link
                   elsif docs.key?(path)
                     docs[path]["url"] + suffix
                   elsif path.casecmp?("README.md")
                     page_data["permalink"] + suffix
                   else
                     "https://github.com/#{@github_user}/#{repo_name}/blob/#{branch}/#{path}#{suffix}"
                   end
          "[#{text}](#{target})"
        end
      end

      # A list of doc links, such as the Documentation section, becomes a row of cards
      def build_doc_cards(content, docs, repo_name, branch)
        lines = content.split("\n", -1)
        output = []
        run = []

        flush = lambda do
          if run.size.positive?
            cards = run.map do |title, url, text|
              text_html = text.to_s.empty? ? "" : "<span class=\"doc-card-text\">#{inline_markdown_html(text)}</span>"
              "  <a class=\"doc-card\" href=\"#{url}\"><span class=\"doc-card-title\">#{inline_markdown_html(title)}</span>#{text_html}</a>"
            end
            output.push("", "<div class=\"doc-cards\">", *cards, "</div>", "")
          end
          run = []
        end

        lines.each do |line|
          match = line.match(DOC_CARD_LINE)
          path, = match && resolve_repo_link("", match[2], repo_name, branch)
          if match && path && docs.key?(path)
            run << [match[1], docs[path]["url"], match[3]]
          else
            flush.call
            output << line
          end
        end
        flush.call
        output.join("\n")
      end

      def inline_markdown_html(text)
        escaped = text.to_s.gsub("&", "&amp;").gsub("<", "&lt;").gsub(">", "&gt;").gsub("\"", "&quot;")
        escaped.gsub(/`([^`]+)`/, "<code>\\1</code>").gsub(/\*\*([^*]+)\*\*/, "<strong>\\1</strong>")
      end

      def write_doc_page(repo_name, branch, path, doc, docs, page_data, showcase)
        base_dir = File.dirname(path) == "." ? "" : File.dirname(path)
        body = strip_utf8_bom(remove_gh_only_sections(doc["body"].gsub("\r\n", "\n")))
        body = body.sub(/\A\s*#\s+[^\n]*\n/, "")
        body = rewrite_asset_links(body, repo_name, branch, base_dir)
        body = inline_showcases(body, base_dir, showcase, repo_name, branch)
        body = rewrite_doc_links(body, base_dir, docs, page_data, repo_name, branch)
        body = normalize_markdown_tables(body)

        page_content = <<~MARKDOWN
          ---
          layout: plugin
          plugin_doc: true
          nav: plugins
          title: "#{escape_yaml("#{page_data["title"]} · #{doc["title"]}")}"
          hero_title: "#{escape_yaml(doc["title"])}"
          hero_subtitle: "#{escape_yaml(repo_name)}"
          thumbnail: "#{escape_yaml(page_data["thumbnail"])}"
          repo: "#{escape_yaml(repo_name)}"
          github: "#{escape_yaml("https://github.com/#{@github_user}/#{repo_name}/blob/#{branch}/#{path}")}"
          permalink: "#{escape_yaml(doc["url"])}"
          discussion: false
          ---

          [&larr; Back to #{page_data["title"]}](#{page_data["permalink"]})

          {% raw %}
          %%DOC_BODY%%
          {% endraw %}

          ---

          > [View this page on GitHub](https://github.com/#{@github_user}/#{repo_name}/blob/#{branch}/#{path})
        MARKDOWN

        destination = File.join(pages_dir, "docs", repo_name, "#{doc_slug(path)}.md")
        FileUtils.mkdir_p(File.dirname(destination))
        File.write(destination, page_content.sub("%%DOC_BODY%%", body.strip))
      end

      def default_banner_url(repo_name, branch)
        return nil if local_repo_dir(repo_name) && !File.file?(File.join(local_repo_dir(repo_name), "Resources", "Banner.png"))

        "https://raw.githubusercontent.com/#{@github_user}/#{repo_name}/refs/heads/#{branch}/Resources/Banner.png"
      end

      def fetch_public_repositories
        results = []
        page = 1

        loop do
          url = "https://api.github.com/users/#{@github_user}/repos?type=public&sort=updated&per_page=100&page=#{page}"
          payload = github_get_json(url)
          break unless payload.is_a?(Array) && !payload.empty?

          results.concat(payload)
          break if payload.size < 100

          page += 1
        end

        results
      end

      def fetch_repository_topics(repo_name)
        payload = github_get_json("https://api.github.com/repos/#{@github_user}/#{repo_name}/topics")
        names = payload.is_a?(Hash) ? payload["names"] : []
        Array(names).map { |topic| topic.to_s.downcase }
      rescue StandardError => e
        Jekyll.logger.warn("[plugin_sync] Failed to fetch topics for #{repo_name}: #{e.message}")
        []
      end

      def repository_allowed?(repo)
        return false if repo.nil?

        repo_name = repo["name"].to_s
        return false if repo_name.empty?
        return false if Array(@config["exclude_repos"]).map(&:to_s).include?(repo_name)
        return false if repo["archived"] && !truthy?(@config["include_archived"])

        true
      end

      def plugin_repository?(repo_name, topics)
        include_repos = Array(@config["include_repos"]).map(&:to_s)
        return true if include_repos.include?(repo_name)

        include_topics = Array(@config["include_topics"]).map { |value| value.to_s.downcase }
        prefix_match = Array(@config["include_repo_prefixes"]).any? do |prefix|
          prefix_string = prefix.to_s
          !prefix_string.empty? && repo_name.start_with?(prefix_string)
        end

        topic_match = !(topics & include_topics).empty?
        return true if topic_match

        return true if include_topics.empty? && prefix_match
        return true if truthy?(@config["allow_prefix_fallback"]) && prefix_match

        false
      end

      def fetch_readme(repo_name, branch)
        url = URI("https://raw.githubusercontent.com/#{@github_user}/#{repo_name}/refs/heads/#{branch}/README.md")
        response = http_get(url)
        return nil unless response.is_a?(Net::HTTPSuccess)

        response.body.to_s.force_encoding("UTF-8")
      rescue StandardError => e
        Jekyll.logger.warn("[plugin_sync] Error fetching README for #{repo_name}: #{e.message}")
        nil
      end

      def normalize_readme(content, repo_name, branch)
        normalized = remove_gh_only_sections(content)
        normalized = strip_utf8_bom(normalized)
        normalized, extracted_meta = extract_meta_block(normalized)
        normalized = rewrite_asset_links(normalized, repo_name, branch)
        normalized = normalize_markdown_tables(normalized)

        if truthy?(@config["download_footer"])
          normalized = normalized.strip + "\n\n---\n\n> [Download on GitHub](https://github.com/#{@github_user}/#{repo_name})\n"
        end

        [normalized.strip + "\n", extracted_meta]
      end

      def strip_utf8_bom(content)
        content.to_s.sub(/\A\uFEFF/, "")
      end

      # Kramdown table parsing is strict and expects a blank line before table blocks.
      # Also normalize separator rows in case non-ASCII dashes sneak in from source markdown.
      def normalize_markdown_tables(content)
        lines = content.to_s.gsub("\r\n", "\n").split("\n", -1)
        lines.map! { |line| normalize_table_separator_line(line) }

        normalized = []
        lines.each_with_index do |line, idx|
          next_line = idx + 1 < lines.length ? lines[idx + 1] : nil
          if markdown_table_header_line?(line) && markdown_table_separator_line?(next_line)
            prev = normalized.last
            normalized << "" unless prev.nil? || prev.strip.empty?
          end
          normalized << line
        end

        normalized.join("\n")
      end

      def markdown_table_header_line?(line)
        stripped = line.to_s.strip
        return false if stripped.empty?
        return false unless stripped.start_with?("|") && stripped.end_with?("|")
        return false if markdown_table_separator_line?(stripped)

        true
      end

      def markdown_table_separator_line?(line)
        stripped = line.to_s.strip
        return false if stripped.empty?
        return false unless stripped.match?(/\A\|?[\s:\-\u2013\u2014|]+\|?\z/)

        inner = stripped.sub(/\A\|/, "").sub(/\|\z/, "")
        cells = inner.split("|").map(&:strip)
        return false if cells.length < 2

        cells.all? { |cell| cell.match?(/\A:?[ \-\u2013\u2014]{1,}:?\z/) }
      end

      def normalize_table_separator_line(line)
        return line unless markdown_table_separator_line?(line)

        indent = line[/^\s*/].to_s
        stripped = line.strip
        has_leading_pipe = stripped.start_with?("|")
        has_trailing_pipe = stripped.end_with?("|")
        inner = stripped.sub(/\A\|/, "").sub(/\|\z/, "")

        rebuilt_cells = inner.split("|").map do |cell|
          token = cell.strip
          next token unless token.match?(/\A:?[ \-\u2013\u2014]{1,}:?\z/)

          left = token.start_with?(":") ? ":" : ""
          right = token.end_with?(":") ? ":" : ""
          "#{left}---#{right}"
        end

        rebuilt = rebuilt_cells.join("|")
        rebuilt = "|#{rebuilt}" if has_leading_pipe
        rebuilt = "#{rebuilt}|" if has_trailing_pipe

        "#{indent}#{rebuilt}"
      end
      def remove_gh_only_sections(content)
        content.gsub(/<!--\s*GH_ONLY_START\s*-->(.*?)<!--\s*GH_ONLY_END\s*-->/m) { kept_doc_sections(Regexp.last_match(1)) }
      end

      # A heading with a list of links to markdown files (the Documentation section) stays on the site as doc cards
      def kept_doc_sections(block)
        sections = block.to_enum(:scan, /^(\#{2,6}[^\n]*)\n((?:[ \t]*[-*][ \t]+\[[^\]]+\]\([^)\s]+\.md(?:#[^)\s]*)?\)[^\n]*(?:\n|\z))+)/i).map do
          match = Regexp.last_match
          "#{match[1]}\n#{match[2]}"
        end
        sections.empty? ? "" : "\n#{sections.join("\n")}\n"
      end

      def extract_meta_block(content)
        metadata = {}
        cleaned = content.gsub(/<!--\s*PLUGIN_META(.*?)PLUGIN_META\s*-->/m) do
          raw_meta = Regexp.last_match(1).to_s.strip
          begin
            parsed = YAML.safe_load(raw_meta)
            if parsed.is_a?(Hash)
              metadata.merge!(stringify_keys(parsed))
            end
          rescue StandardError => e
            Jekyll.logger.warn("[plugin_sync] Could not parse PLUGIN_META block: #{e.message}")
          end
          ""
        end

        [cleaned, metadata]
      end

      def rewrite_asset_links(content, repo_name, branch, base_dir = "")
        raw_base = "https://raw.githubusercontent.com/#{@github_user}/#{repo_name}/refs/heads/#{branch}/"
        raw_base += "#{base_dir}/" unless base_dir.to_s.empty?

        rewritten = content.gsub(/!\[([^\]]*)\]\(([^)]+)\)/) do
          alt_text = Regexp.last_match(1)
          link = Regexp.last_match(2)
          "![#{alt_text}](#{absolutize_media_url(link, raw_base, repo_name, branch)})"
        end

        rewritten.gsub(/(<(?:img|video|source)\b[^>]*?\s(?:src|poster)=["'])([^"']+)(["'])/i) do
          prefix = Regexp.last_match(1)
          link = Regexp.last_match(2)
          suffix = Regexp.last_match(3)
          "#{prefix}#{absolutize_media_url(link, raw_base, repo_name, branch)}#{suffix}"
        end
      end

      def absolutize_media_url(link, raw_base, repo_name, branch)
        original = link.to_s.strip
        return original if original.empty?
        return original if original.start_with?("#")
        return original if original.match?(/\A(?:mailto|data|javascript):/i)

        blob_to_raw = github_blob_to_raw(original, raw_base, repo_name, branch)
        return blob_to_raw unless blob_to_raw.nil?

        return original if original.match?(/\Ahttps?:\/\//i)

        path = original.sub(/\A\.\//, "")
        path = path.sub(%r{\A/}, "")
        URI.join(raw_base, path).to_s
      rescue StandardError
        original
      end

      def github_blob_to_raw(url, raw_base, repo_name, branch)
        uri = URI.parse(url)
        return nil unless uri.host == "github.com"

        parts = uri.path.split("/")
        return nil if parts.size < 6
        return nil unless parts[1] == @github_user && parts[2] == repo_name
        return nil unless parts[3] == "blob" && parts[4] == branch

        blob_path = parts[5..].join("/")
        URI.join(raw_base, blob_path).to_s
      rescue StandardError
        nil
      end

      def build_page_data(repo, topics, meta, branch)
        repo_name = repo["name"].to_s
        overrides = stringify_keys((@config["repo_overrides"] || {})[repo_name] || {})

        short_description = first_present(
          overrides["short-description"],
          overrides["short_description"],
          meta["short-description"],
          meta["short_description"],
          repo["description"],
          "Unreal Engine plugin"
        )

        title_value = first_present(overrides["title"], meta["title"], humanize_repo_name(repo_name))
        description_value = first_present(overrides["description"], meta["description"], short_description)
        category_value = first_present(
          overrides["category"],
          meta["category"],
          category_from_topics(topics),
          @config["default_category"]
        )
        thumbnail_value = first_present(
          overrides["thumbnail"],
          meta["thumbnail"],
          default_banner_url(repo_name, branch),
          @config["default_thumbnail"]
        )

        permalink_value = first_present(
          overrides["permalink"],
          meta["permalink"],
          "/plugins/#{slugify(repo_name)}/"
        )

        discussion_data = build_discussion_data(repo_name, repo, overrides, meta)
        date_value = parse_date(first_present(overrides["date"], meta["date"], repo["pushed_at"], repo["created_at"]))
        {
          "title" => title_value,
          "short-description" => short_description,
          "description" => description_value,
          "category" => category_value,
          "thumbnail" => thumbnail_value,
          "date" => date_value.strftime("%Y-%m-%d"),
          "topics" => topics,
          "github" => repo["html_url"].to_s.empty? ? "https://github.com/#{@github_user}/#{repo_name}" : repo["html_url"].to_s,
          "permalink" => permalink_value,
          "discussion" => discussion_data["enabled"],
          "discussion_mapping" => discussion_data["mapping"],
          "discussion_term" => discussion_data["term"],
          "discussion_repo" => discussion_data["repo"],
          "discussion_repo_id" => discussion_data["repo_id"],
          "discussion_category" => discussion_data["category"],
          "discussion_category_id" => discussion_data["category_id"],
          "discussion_configured" => discussion_data["configured"]
        }
      end

